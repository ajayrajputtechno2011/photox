    const galleryImages = [...document.querySelectorAll('.gallery-grid img')];
    const lightbox = document.getElementById('detailLightbox');
    const lightboxImage = document.getElementById('lightboxImage');
    const lightboxCaption = document.getElementById('lightboxCaption');
    let photoIndex = 0;

    function showPhoto(index) {
      photoIndex = (index + galleryImages.length) % galleryImages.length;
      const source = galleryImages[photoIndex];
      lightboxImage.src = source.src;
      lightboxImage.alt = source.alt;
      lightboxCaption.textContent = `${photoIndex + 1} / ${galleryImages.length} · ${source.alt}`;
    }

    function closeLightbox() {
      lightbox.classList.remove('is-open');
      document.body.classList.remove('lightbox-open');
    }

    galleryImages.forEach((image, index) => image.addEventListener('click', () => {
      showPhoto(index);
      lightbox.classList.add('is-open');
      document.body.classList.add('lightbox-open');
      document.getElementById('lightboxClose').focus();
    }));
    document.getElementById('lightboxPrev').addEventListener('click', () => showPhoto(photoIndex - 1));
    document.getElementById('lightboxNext').addEventListener('click', () => showPhoto(photoIndex + 1));
    document.getElementById('lightboxClose').addEventListener('click', closeLightbox);
    lightbox.addEventListener('click', (event) => { if (event.target === lightbox) closeLightbox(); });
    document.addEventListener('keydown', (event) => {
      if (!lightbox.classList.contains('is-open')) return;
      if (event.key === 'Escape') closeLightbox();
      if (event.key === 'ArrowLeft') showPhoto(photoIndex - 1);
      if (event.key === 'ArrowRight') showPhoto(photoIndex + 1);
    });

    const relatedTrack = document.getElementById('relatedTrack');
    const relatedCards = [...document.querySelectorAll('.related-card')];
    let relatedIndex = 0;

    function moveRelated(direction = 0) {
      const perView = window.innerWidth <= 575 ? 1 : window.innerWidth <= 991 ? 2 : 3;
      const maxIndex = Math.max(0, relatedCards.length - perView);
      relatedIndex = Math.min(Math.max(relatedIndex + direction, 0), maxIndex);
      const step = relatedCards[0].getBoundingClientRect().width + 20;
      relatedTrack.style.transform = `translateX(-${relatedIndex * step}px)`;
      document.getElementById('relatedPrev').disabled = relatedIndex === 0;
      document.getElementById('relatedNext').disabled = relatedIndex === maxIndex;
    }

    document.getElementById('relatedPrev').addEventListener('click', () => moveRelated(-1));
    document.getElementById('relatedNext').addEventListener('click', () => moveRelated(1));
    window.addEventListener('resize', () => moveRelated());
    moveRelated();
  </script>
